"""
utils for self-bootstrapping vulpix's config and applying `$VULPIX_DATA/bootstrapped.json` if it
exists (see `docs/bootstrap.md`).
"""

import fileinput
import shutil
from dataclasses import dataclass
from importlib.resources import as_file, files
from pathlib import Path

from vulpix import utils
from vulpix.core import VulpixError, dirs, logging

default_blueprint_path = dirs.VULPIX_CONFIG / "blueprint.yaml"
quickstart_config = files("vulpix").joinpath("resources/quickstart_config")


def run_quickstart_config_check(logger: logging.Logger):
    """checks if quickstart config should be used"""
    if not default_blueprint_path.exists():
        logger.error("blueprint does not exist")
        use_entire_quickstart = not dirs.VULPIX_CONFIG.exists() or not any(
            dirs.VULPIX_CONFIG.iterdir()
        )
        if not use_entire_quickstart:
            logger.info("copying quickstart blueprint")
            prompt = "want to copy the entire quickstart config (optional, will overwrite config dir)?"
            use_entire_quickstart = utils.verify(prompt)

        with as_file(quickstart_config) as quickstart_dir:
            if use_entire_quickstart:
                logger.info(f"copying quickstart config to '{dirs.VULPIX_CONFIG}'")
                utils.rm_fr(dirs.VULPIX_CONFIG)
                utils.cp_r(quickstart_dir, dirs.VULPIX_CONFIG)
            else:
                shutil.copy2(quickstart_dir / "blueprint.yaml", dirs.VULPIX_CONFIG)


@dataclass
class BootstrappedPackages:
    packages: dict[str, list[str]]  # like {manager: packages}


bootstrapped_path = dirs.VULPIX_DATA / "bootstrapped.json"
bootstrapped_datafile = utils.DataclassFile(
    bootstrapped_path,
    dclass=BootstrappedPackages,
    lock_file=False,
    on_error=(lambda _, e: VulpixError(f"invalid bootstrapped.json: {e}")),
)


def run_bootstrapped_packages_check(blueprint_path: Path, logger: logging.Logger):
    """checks for `$VULPIX_DATA/bootstrapped.json` and if exists, applies to blueprint"""
    if bootstrapped_path.exists():
        logger.info("looks like bootstrap script bootstrapped some packages")

        bootstrapped = bootstrapped_datafile.loadf()
        logger.debug(f"bootstrapped: {bootstrapped}")
        logger.info("adding bootstrapped packages to blueprint")

        # insert autogenerated bootstrap packages into existing blueprint
        #
        # NOTE: this is done very lazily and will probably break the yaml syntax of any other
        # existing blueprint besides the quickstart one
        packages_yaml = [
            f"  {manager}: [{', '.join(packages)}] #autogenerated by bootstrap"
            for manager, packages in bootstrapped.packages.items()
        ]
        with fileinput.input(blueprint_path, inplace=True) as file:
            for line in file:
                # we're trying to insert packages_yaml lines after the "packages:" line
                if line.strip().startswith("packages:"):
                    print("packages:")
                    print("\n".join(packages_yaml) + "\n")
                else:
                    print(line, end="")  # don't change anything

        # remove bootstrapped.json when we're done
        bootstrapped_path.unlink()
